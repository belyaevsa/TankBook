/// Two receipts as the iOS 27 simulator's Vision reads them - the lines and
/// their positions verbatim - so what the phone's recognizer does to them is
/// checked on every runtime, not only on the measured one. On iOS the `=`
/// before an amount reads as `5` or `#` and one digit of a printed fuel line
/// flips; the thumb over receipt-057's price hides its leading `6`.
@Suite("Receipts as iOS 27 reads them")
struct ReceiptIOS27ReadsTests {
    private static func lines(_ rows: [(Double, Double, String)]) -> [OCRLine] {
        rows.map { x, y, text in
            OCRLine(text: text, boundingBox: CGRect(x: x - 0.1, y: y - 0.008, width: 0.2, height: 0.016))
        }
    }

    private static func extractor() throws -> FuelExtractor {
        FuelExtractor(bandProvider: DefaultFuelPriceBandProvider(pack: try FuelPriceBandStore.bundledPack()))
    }

    @Test("a printed fuel line its own operands and the document's accounting contradict is not the total")
    func misreadFuelLineAmount() throws {
        // `43.38 Х 38.28` = 1660.59; beside it iOS reads `#1680.59`; ИТОГ
        // 1729.87 less the service line's `69.28 X 1` is 1660.59 again.
        let result = try Self.extractor().extract(lines: Self.lines(Self.receipt025), source: .receipt)
        #expect(result.total == Decimal(string: "1660.59"))
    }

    @Test("the operand that makes the total an impossible price is not the volume")
    func occludedPriceIsNotTheVolume() throws {
        // `<9.05 x 57.000` with `=3935.85`: 3935.85 / 9.05 is no fuel price in
        // roubles, 3935.85 / 57.000 = 69.05 is.
        let result = try Self.extractor().extract(lines: Self.lines(Self.receipt057), source: .receipt)
        #expect(result.liters == 57.0)
        #expect(result.unitPrice != Decimal(string: "57"))
        #expect(result.total == Decimal(string: "3935.85"))
    }

    @Test("a unit legend's '= 1 litre' is not the volume")
    func unitLegendIsNotTheVolume() throws {
        // iOS reads the quantity header `единиц` as `единий`, so no label names
        // the 30.00 below it; the only litre-marked line left is the legend
        // `:1 Ел. =1 ЛИТР ДЛЯ НЕФТЕПРОДУКТОВ`, which must not become 1.0 L.
        let result = try Self.extractor().extract(lines: Self.lines(Self.receipt062), source: .receipt)
        #expect(result.liters != 1.0)
        #expect(result.liters == nil || result.liters == 30.0)
    }

    @Test("a volume a corroborated total and a marked price both contradict is not committed")
    func volumeOutvotedByTotalAndPrice() throws {
        // iOS reads `43.25L` as `13.25L`; `90,78` is printed three times and
        // `2,099 EUR/L` carries its unit. The volume abstains - never the quotient.
        let result = try Self.extractor().extract(lines: Self.lines(Self.receipt083), source: .receipt)
        #expect(result.liters == nil)
        #expect(result.total == Decimal(string: "90.78"))
    }

